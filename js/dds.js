const BC7_W2 = [0, 21, 43, 64];
const BC7_W3 = [0, 9, 18, 27, 37, 46, 55, 64];
const BC7_W4 = [0, 4, 9, 13, 17, 21, 26, 30, 34, 38, 43, 47, 51, 55, 60, 64];
const BC7_COLOR_BITS = [4, 6, 5, 7, 5, 7, 7, 5];
const BC7_ALPHA_BITS = [0, 0, 0, 0, 6, 8, 7, 5];
const BC7_HAS_PBITS = 0b11001011;

function bc7Block(src, off, dst, dstW, bx, by) {
  let pos = 0;
  const bit = () => {
    const v = (src[off + (pos >> 3)] >> (pos & 7)) & 1;
    pos++;
    return v;
  };
  const bits = (n) => {
    let v = 0;
    for (let i = 0; i < n; i++) v |= bit() << i;
    return v;
  };
  const put = (x, y, r, g, b, a) => {
    const o = ((by + y) * dstW + bx + x) * 4;
    dst[o] = r; dst[o + 1] = g; dst[o + 2] = b; dst[o + 3] = a;
  };

  let mode = 0;
  while (mode < 8 && bit() === 0) mode++;
  if (mode >= 8) {
    for (let y = 0; y < 4; y++) for (let x = 0; x < 4; x++) put(x, y, 0, 0, 0, 0);
    return;
  }

  let partition = 0, nParts = 1, rotation = 0, isb = 0;
  if (mode === 0 || mode === 1 || mode === 2 || mode === 3 || mode === 7) {
    nParts = (mode === 0 || mode === 2) ? 3 : 2;
    partition = bits(mode === 0 ? 4 : 6);
  }
  const nEnd = nParts * 2;
  if (mode === 4 || mode === 5) {
    rotation = bits(2);
    if (mode === 4) isb = bit();
  }

  const ep = [];
  for (let j = 0; j < nEnd; j++) ep.push([0, 0, 0, 0]);
  for (let i = 0; i < 3; i++)
    for (let j = 0; j < nEnd; j++) ep[j][i] = bits(BC7_COLOR_BITS[mode]);
  if (BC7_ALPHA_BITS[mode] > 0)
    for (let j = 0; j < nEnd; j++) ep[j][3] = bits(BC7_ALPHA_BITS[mode]);

  if (mode === 0 || mode === 1 || mode === 3 || mode === 6 || mode === 7) {
    for (let i = 0; i < nEnd; i++) for (let k = 0; k < 4; k++) ep[i][k] <<= 1;
    if (mode === 1) {
      const p0 = bit(), p1 = bit();
      for (let k = 0; k < 3; k++) {
        ep[0][k] |= p0; ep[1][k] |= p0;
        ep[2][k] |= p1; ep[3][k] |= p1;
      }
    } else if (BC7_HAS_PBITS & (1 << mode)) {
      for (let i = 0; i < nEnd; i++) {
        const p = bit();
        for (let k = 0; k < 4; k++) ep[i][k] |= p;
      }
    }
  }
  const pb = (BC7_HAS_PBITS >> mode) & 1;
  for (let i = 0; i < nEnd; i++) {
    let n = BC7_COLOR_BITS[mode] + pb;
    for (let k = 0; k < 3; k++) {
      ep[i][k] = (ep[i][k] << (8 - n)) & 0xff;
      ep[i][k] |= ep[i][k] >> n;
    }
    n = BC7_ALPHA_BITS[mode] + pb;
    ep[i][3] = (ep[i][3] << (8 - n)) & 0xff;
    ep[i][3] |= ep[i][3] >> n;
  }
  if (!BC7_ALPHA_BITS[mode]) for (let j = 0; j < nEnd; j++) ep[j][3] = 0xff;

  const ib = (mode === 0 || mode === 1) ? 3 : (mode === 6 ? 4 : 2);
  const ib2 = mode === 4 ? 3 : (mode === 5 ? 2 : 0);
  const w1 = ib === 2 ? BC7_W2 : (ib === 3 ? BC7_W3 : BC7_W4);
  const w2 = ib2 === 2 ? BC7_W2 : BC7_W3;
  const setOf = (t) => nParts === 1 ? (t ? 0 : 128)
    : BC7_PARTITIONS[((nParts - 2) * 64 + partition) * 16 + t];

  const idx = new Uint8Array(16);
  for (let t = 0; t < 16; t++) {
    let n = ib;
    if (setOf(t) & 0x80) n--;
    idx[t] = bits(n);
  }
  const lerp = (e0, e1, w, i) => (e0 * (64 - w[i]) + e1 * w[i] + 32) >> 6;
  for (let t = 0; t < 16; t++) {
    const s = setOf(t) & 0x03;
    const a0 = ep[s * 2], a1 = ep[s * 2 + 1];
    const i1 = idx[t];
    let r, g, b, a;
    if (!ib2) {
      r = lerp(a0[0], a1[0], w1, i1); g = lerp(a0[1], a1[1], w1, i1);
      b = lerp(a0[2], a1[2], w1, i1); a = lerp(a0[3], a1[3], w1, i1);
    } else {
      const i2 = bits(t ? ib2 : ib2 - 1);
      if (!isb) {
        r = lerp(a0[0], a1[0], w1, i1); g = lerp(a0[1], a1[1], w1, i1);
        b = lerp(a0[2], a1[2], w1, i1); a = lerp(a0[3], a1[3], w2, i2);
      } else {
        r = lerp(a0[0], a1[0], w2, i2); g = lerp(a0[1], a1[1], w2, i2);
        b = lerp(a0[2], a1[2], w2, i2); a = lerp(a0[3], a1[3], w1, i1);
      }
    }
    if (rotation === 1) [a, r] = [r, a];
    else if (rotation === 2) [a, g] = [g, a];
    else if (rotation === 3) [a, b] = [b, a];
    put(t & 3, t >> 2, r, g, b, a);
  }
}

function bc1ColorBlock(src, off, dst, dstW, bx, by, opaqueOnly) {
  const c0 = src[off] | (src[off + 1] << 8);
  const c1 = src[off + 2] | (src[off + 3] << 8);
  const r0 = (c0 >> 11) & 0x1f, g0 = (c0 >> 5) & 0x3f, b0 = c0 & 0x1f;
  const r1 = (c1 >> 11) & 0x1f, g1 = (c1 >> 5) & 0x3f, b1 = c1 & 0x1f;
  const ref = [
    [(r0 * 527 + 23) >> 6, (g0 * 259 + 33) >> 6, (b0 * 527 + 23) >> 6, 255],
    [(r1 * 527 + 23) >> 6, (g1 * 259 + 33) >> 6, (b1 * 527 + 23) >> 6, 255],
  ];
  if (c0 > c1 || opaqueOnly) {
    ref.push([((2 * r0 + r1) * 351 + 61) >> 7, ((2 * g0 + g1) * 2763 + 1039) >> 11,
              ((2 * b0 + b1) * 351 + 61) >> 7, 255]);
    ref.push([((r0 + r1 * 2) * 351 + 61) >> 7, ((g0 + g1 * 2) * 2763 + 1039) >> 11,
              ((b0 + b1 * 2) * 351 + 61) >> 7, 255]);
  } else {
    ref.push([((r0 + r1) * 1053 + 125) >> 8, ((g0 + g1) * 4145 + 1019) >> 11,
              ((b0 + b1) * 1053 + 125) >> 8, 255]);
    ref.push([0, 0, 0, 0]);
  }
  let bitsv = (src[off + 4] | (src[off + 5] << 8) | (src[off + 6] << 16) | (src[off + 7] << 24)) >>> 0;
  for (let t = 0; t < 16; t++) {
    const c = ref[bitsv & 3];
    bitsv >>>= 2;
    const o = ((by + (t >> 2)) * dstW + bx + (t & 3)) * 4;
    dst[o] = c[0]; dst[o + 1] = c[1]; dst[o + 2] = c[2]; dst[o + 3] = c[3];
  }
}

function bc3AlphaBlock(src, off, dst, dstW, bx, by) {
  const a0 = src[off], a1 = src[off + 1];
  const al = [a0, a1];
  if (a0 > a1) {
    for (let k = 1; k <= 6; k++) al.push(Math.floor(((7 - k) * a0 + k * a1) / 7));
  } else {
    for (let k = 1; k <= 4; k++) al.push(Math.floor(((5 - k) * a0 + k * a1) / 5));
    al.push(0, 255);
  }
  // 48 bits of 3-bit indices, read as two 24-bit halves to stay in int range
  const lo = src[off + 2] | (src[off + 3] << 8) | (src[off + 4] << 16);
  const hi = src[off + 5] | (src[off + 6] << 8) | (src[off + 7] << 16);
  for (let t = 0; t < 16; t++) {
    const v = t < 8 ? (lo >> (t * 3)) & 7 : (hi >> ((t - 8) * 3)) & 7;
    dst[((by + (t >> 2)) * dstW + bx + (t & 3)) * 4 + 3] = al[v];
  }
}

/* Decode a .dds file (ArrayBuffer / Uint8Array). Returns
   {width, height, data: Uint8ClampedArray RGBA} or throws. */
function decodeDDS(buf) {
  const u8 = buf instanceof Uint8Array ? buf : new Uint8Array(buf);
  const dv = new DataView(u8.buffer, u8.byteOffset, u8.byteLength);
  if (dv.getUint32(0, true) !== 0x20534444) throw new Error("not a DDS file");
  const height = dv.getUint32(12, true), width = dv.getUint32(16, true);
  const four = String.fromCharCode(u8[84], u8[85], u8[86], u8[87]);
  let off = 128, fmt;
  if (four === "DX10") {
    const dxgi = dv.getUint32(128, true);
    off += 20;
    if (dxgi === 98 || dxgi === 99) fmt = "BC7";
    else if (dxgi === 71 || dxgi === 72) fmt = "BC1";
    else if (dxgi === 77 || dxgi === 78) fmt = "BC3";
    else throw new Error("unsupported DXGI format " + dxgi);
  } else if (four === "DXT1") fmt = "BC1";
  else if (four === "DXT5") fmt = "BC3";
  else throw new Error("unsupported DDS format " + JSON.stringify(four));

  const bw = Math.ceil(width / 4), bh = Math.ceil(height / 4);
  const pw = bw * 4, ph = bh * 4;
  const full = new Uint8ClampedArray(pw * ph * 4);
  const size = fmt === "BC1" ? 8 : 16;
  if (off + bw * bh * size > u8.length) throw new Error("truncated DDS");
  for (let y = 0; y < bh; y++) {
    for (let x = 0; x < bw; x++) {
      const o = off + (y * bw + x) * size;
      if (fmt === "BC7") bc7Block(u8, o, full, pw, x * 4, y * 4);
      else if (fmt === "BC1") bc1ColorBlock(u8, o, full, pw, x * 4, y * 4, false);
      else {
        bc1ColorBlock(u8, o + 8, full, pw, x * 4, y * 4, true);
        bc3AlphaBlock(u8, o, full, pw, x * 4, y * 4);
      }
    }
  }
  if (pw === width && ph === height) return { width, height, data: full };
  const data = new Uint8ClampedArray(width * height * 4);
  for (let y = 0; y < height; y++)
    data.set(full.subarray(y * pw * 4, (y * pw + width) * 4), y * width * 4);
  return { width, height, data };
}

